#!/usr/bin/env node
/**
 * Executable validation for new governance rulesets:
 *   cli-release  — rulesets/cli/release-readiness.rules.json
 *   cli-parity   — rulesets/cli/core-parity.rules.json
 *   evidence     — rulesets/evidence/evidence-manifest.rules.json
 *   mcp          — rulesets/mcp/protocol-compliance.rules.json
 *   observability — rulesets/observability/telemetry-evidence.rules.json
 */

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// Script lives at <root>/.harness/scripts/validate-rulesets.mjs
const root = path.resolve(__dirname, '..', '..');
const cliDir = path.join(root, 'sdk', 'cli');
const failures = [];
const warnings = [];
const passed = [];

function pass(ruleId, title) {
  passed.push({ ruleId, title });
  console.log(`  ✓ [${ruleId}] ${title}`);
}

function fail(ruleId, title, detail, blocking = true) {
  const entry = { ruleId, title, detail, blocking };
  if (blocking) {
    failures.push(entry);
    console.error(`  ✗ [${ruleId}] ${title}\n      ${detail}`);
  } else {
    warnings.push(entry);
    console.warn(`  ~ [${ruleId}] ${title}\n      ${detail}`);
  }
}

function fileExists(p) {
  return fs.existsSync(p);
}

function dirExists(p) {
  return fs.existsSync(p) && fs.statSync(p).isDirectory();
}

// ──────────────────────────────────────────────────────────────────────────────
// CLI Release Readiness
// ──────────────────────────────────────────────────────────────────────────────
console.log('\n▶ CLI Release Readiness (cli-release)');

// CLI-RR-01: TypeScript build must have produced dist/
{
  const distMain = path.join(cliDir, 'dist', 'main.js');
  if (fileExists(distMain)) {
    pass('CLI-RR-01', 'TypeScript Build Must Pass');
  } else {
    fail('CLI-RR-01', 'TypeScript Build Must Pass',
      `dist/main.js not found under ${cliDir} — run npm run build first`);
  }
}

// CLI-RR-02: Test runner must succeed (check last known result via dist existence; live run optional)
{
  const runLive = process.argv.includes('--run-tests');
  if (runLive) {
    try {
      execSync('node --max-old-space-size=8192 node_modules/.bin/jest --runInBand --silent', {
        cwd: cliDir, stdio: 'pipe', timeout: 300_000,
      });
      pass('CLI-RR-02', 'Unit and Integration Tests Must Start and Pass');
    } catch {
      fail('CLI-RR-02', 'Unit and Integration Tests Must Start and Pass',
        'jest exited non-zero — see npm test output for details');
    }
  } else {
    // Static proxy: presence of compiled test artefacts + dist is a reasonable gate without --run-tests
    const distSpec = path.join(cliDir, 'dist', 'core', 'mcp', 'server.spec.js');
    if (fileExists(distSpec)) {
      pass('CLI-RR-02', 'Unit and Integration Tests Must Start and Pass (static proxy — use --run-tests for live)');
    } else {
      fail('CLI-RR-02', 'Unit and Integration Tests Must Start and Pass',
        'Compiled test artefacts missing. Run npm run build then npm test -- --runInBand');
    }
  }
}

// CLI-RR-03: package-lock.json committed (lives at workspace root in npm workspaces)
{
  const rootLock = path.join(root, 'package-lock.json');
  const cliLock = path.join(cliDir, 'package-lock.json');
  if (fileExists(rootLock) || fileExists(cliLock)) {
    pass('CLI-RR-03', 'Dependency Graph Must Be Reproducible');
  } else {
    fail('CLI-RR-03', 'Dependency Graph Must Be Reproducible',
      `package-lock.json not found at ${rootLock} or ${cliLock}`);
  }
}

// CLI-RR-04: MCP smoke evidence present (generated by mcp-smoke.mjs)
{
  const evidenceFile = path.join(root, '.harness', 'evidence', 'mcp-smoke.evidence.json');
  if (fileExists(evidenceFile)) {
    const ev = JSON.parse(fs.readFileSync(evidenceFile, 'utf8'));
    const initOk = ev?.results?.initialize?.ok === true;
    const toolsOk = ev?.results?.['tools/list']?.ok === true;
    if (initOk && toolsOk) {
      pass('CLI-RR-04', 'MCP Smoke Test Must Pass');
    } else {
      fail('CLI-RR-04', 'MCP Smoke Test Must Pass',
        `smoke evidence found but initialize=${initOk} tools/list=${toolsOk} — re-run mcp-smoke.mjs`);
    }
  } else {
    fail('CLI-RR-04', 'MCP Smoke Test Must Pass',
      `No smoke evidence at .harness/evidence/mcp-smoke.evidence.json — run .harness/scripts/mcp-smoke.mjs`);
  }
}

// CLI-RR-05: README docs present (SHOULD)
{
  const cliReadme = path.join(cliDir, 'README.md');
  const archDoc = path.join(cliDir, 'ARCHITECTURE.md');
  const missing = [cliReadme, archDoc].filter(p => !fileExists(p));
  if (missing.length === 0) {
    pass('CLI-RR-05', 'Release Documentation Must Match Implementation');
  } else {
    fail('CLI-RR-05', 'Release Documentation Must Match Implementation',
      `Missing docs: ${missing.map(p => path.relative(root, p)).join(', ')}`, false);
  }
}

// ──────────────────────────────────────────────────────────────────────────────
// CLI/Core Parity
// ──────────────────────────────────────────────────────────────────────────────
console.log('\n▶ CLI/Core Parity (cli-parity)');

// CLI-PAR-01: Every ruleset has a matching CLI command or MCP tool handler
{
  const rulesetsDir = path.join(root, 'rulesets');
  const commandsDir = path.join(cliDir, 'src', 'commands');
  const toolsDir = path.join(cliDir, 'src', 'core', 'mcp', 'tools');

  const rulesetDirs = fs.existsSync(rulesetsDir)
    ? fs.readdirSync(rulesetsDir).filter(e => {
        const ep = path.join(rulesetsDir, e);
        return fs.statSync(ep).isDirectory();
      })
    : [];

  const commandNames = fs.existsSync(commandsDir)
    ? fs.readdirSync(commandsDir)
    : [];
  const toolFiles = fs.existsSync(toolsDir)
    ? fs.readdirSync(toolsDir)
    : [];

  const hasValidateCommand = commandNames.some(c => c.includes('validate'));
  const hasMcpValidateTool = toolFiles.some(f => f.includes('validate'));

  if (hasValidateCommand && hasMcpValidateTool) {
    pass('CLI-PAR-01', 'Every Executable Core Rule Has a Parity Record');
  } else {
    fail('CLI-PAR-01', 'Every Executable Core Rule Has a Parity Record',
      `validate command: ${hasValidateCommand}, MCP validate tool: ${hasMcpValidateTool}`);
  }
}

// CLI-PAR-02: CLI and MCP use shared RulesetValidatorService
{
  const sharedService = path.join(cliDir, 'src', 'core', 'validators', 'ruleset-validator.service.ts');
  const validateToolPath = path.join(cliDir, 'src', 'core', 'mcp', 'tools', 'validate.ts');
  const validateCmdPath = path.join(cliDir, 'src', 'commands', 'validate', 'validate.command.ts');

  const toolUsesShared = fs.existsSync(validateToolPath) &&
    fs.readFileSync(validateToolPath, 'utf8').includes('RulesetValidatorService');
  const cmdUsesShared = fs.existsSync(validateCmdPath) &&
    fs.readFileSync(validateCmdPath, 'utf8').includes('RulesetValidatorService');

  if (toolUsesShared && cmdUsesShared) {
    pass('CLI-PAR-02', 'CLI and MCP Must Use Shared Validation Logic');
  } else {
    fail('CLI-PAR-02', 'CLI and MCP Must Use Shared Validation Logic',
      `MCP tool uses shared: ${toolUsesShared}, CLI command uses shared: ${cmdUsesShared}`);
  }
}

// CLI-PAR-03: Paired fixture tests exist (spec files for both CLI validate and MCP validate tool)
{
  const cliSpec = path.join(cliDir, 'src', 'commands', 'validate', 'validate.command.spec.ts');
  const mcpSpec = path.join(cliDir, 'src', 'core', 'mcp', 'tools', 'validate.spec.ts');
  const missing = [cliSpec, mcpSpec].filter(p => !fileExists(p));
  if (missing.length === 0) {
    pass('CLI-PAR-03', 'Equivalent CLI and MCP Results Must Be Semantically Consistent');
  } else {
    fail('CLI-PAR-03', 'Equivalent CLI and MCP Results Must Be Semantically Consistent',
      `Missing spec files: ${missing.map(p => path.relative(root, p)).join(', ')}`);
  }
}

// CLI-PAR-04: Parity gaps documented (SHOULD)
{
  const parityTracking = [
    path.join(root, 'reference', 'governance', 'standards', 'cli-core-parity-tracking.md'),
    path.join(root, 'reference', 'governance', 'standards', 'cli-core-parity-tracking.es.md'),
  ];
  const anyMissing = parityTracking.filter(p => !fileExists(p));
  if (anyMissing.length === 0) {
    pass('CLI-PAR-04', 'Parity Gaps Must Remain Visible');
  } else {
    fail('CLI-PAR-04', 'Parity Gaps Must Remain Visible',
      `Missing parity tracking docs: ${anyMissing.map(p => path.relative(root, p)).join(', ')}`, false);
  }
}

// ──────────────────────────────────────────────────────────────────────────────
// Evidence Manifest
// ──────────────────────────────────────────────────────────────────────────────
console.log('\n▶ Evidence Manifest (evidence)');

const evidenceDir = path.join(root, '.harness', 'evidence');
const evidenceFiles = fs.existsSync(evidenceDir)
  ? fs.readdirSync(evidenceDir).filter(f => f.endsWith('.evidence.json'))
  : [];

if (evidenceFiles.length === 0) {
  fail('EVD-01', 'Evidence Has Stable Identity',
    `No evidence files found in .harness/evidence/ — run mcp-smoke.mjs to generate evidence`);
  fail('EVD-02', 'Evidence Links to Source Artifact',
    'No evidence files to validate');
  fail('EVD-03', 'Evidence Captures Validation Outcome',
    'No evidence files to validate');
  fail('EVD-04', 'Evidence Declares Retention Expectation',
    'No evidence files to validate', false);
} else {
  let evd01ok = true, evd02ok = true, evd03ok = true, evd04ok = true;
  for (const f of evidenceFiles) {
    const content = JSON.parse(fs.readFileSync(path.join(evidenceDir, f), 'utf8'));
    const hasIdentity = content.id && content.source && content.generatedAt && content.producer;
    const hasSourceRef = !!content.sourceRef;
    const hasOutcome = content.status !== undefined && content.evaluatedRules !== undefined;
    const hasRetention = !!content.retentionPeriod && !!content.owner;
    if (!hasIdentity) evd01ok = false;
    if (!hasSourceRef) evd02ok = false;
    if (!hasOutcome) evd03ok = false;
    if (!hasRetention) evd04ok = false;
  }
  evd01ok ? pass('EVD-01', 'Evidence Has Stable Identity') :
    fail('EVD-01', 'Evidence Has Stable Identity', 'One or more evidence files missing id, source, generatedAt, or producer');
  evd02ok ? pass('EVD-02', 'Evidence Links to Source Artifact') :
    fail('EVD-02', 'Evidence Links to Source Artifact', 'One or more evidence files missing sourceRef');
  evd03ok ? pass('EVD-03', 'Evidence Captures Validation Outcome') :
    fail('EVD-03', 'Evidence Captures Validation Outcome', 'One or more evidence files missing status or evaluatedRules');
  evd04ok ? pass('EVD-04', 'Evidence Declares Retention Expectation') :
    fail('EVD-04', 'Evidence Declares Retention Expectation', 'One or more evidence files missing retentionPeriod or owner', false);
}

// ──────────────────────────────────────────────────────────────────────────────
// MCP Protocol Compliance
// ──────────────────────────────────────────────────────────────────────────────
console.log('\n▶ MCP Protocol Compliance (mcp)');

// MCP-01 / MCP-02: Verify via smoke evidence
{
  const smokeEvidence = path.join(evidenceDir, 'mcp-smoke.evidence.json');
  if (fileExists(smokeEvidence)) {
    const ev = JSON.parse(fs.readFileSync(smokeEvidence, 'utf8'));

    const initResult = ev?.results?.initialize;
    if (initResult?.ok && initResult?.response?.protocolVersion && initResult?.response?.capabilities) {
      pass('MCP-01', 'Initialize Request Must Return Capabilities');
    } else {
      fail('MCP-01', 'Initialize Request Must Return Capabilities',
        `initialize ok=${initResult?.ok}, protocolVersion=${!!initResult?.response?.protocolVersion}, capabilities=${!!initResult?.response?.capabilities}`);
    }

    const toolsResult = ev?.results?.['tools/list'];
    if (toolsResult?.ok && Array.isArray(toolsResult?.response?.tools) && toolsResult.response.tools.length > 0) {
      pass('MCP-02', 'Tools List Must Be Complete and Stable');
    } else {
      fail('MCP-02', 'Tools List Must Be Complete and Stable',
        `tools/list ok=${toolsResult?.ok}, tools count=${toolsResult?.response?.tools?.length ?? 'n/a'}`);
    }

    const resourcesResult = ev?.results?.['resources/list'];
    if (resourcesResult?.ok) {
      pass('MCP-03', 'Resources Must Preserve Core Traceability');
    } else {
      fail('MCP-03', 'Resources Must Preserve Core Traceability',
        `resources/list ok=${resourcesResult?.ok}`);
    }
  } else {
    fail('MCP-01', 'Initialize Request Must Return Capabilities',
      'No smoke evidence — run .harness/scripts/mcp-smoke.mjs');
    fail('MCP-02', 'Tools List Must Be Complete and Stable',
      'No smoke evidence — run .harness/scripts/mcp-smoke.mjs');
    fail('MCP-03', 'Resources Must Preserve Core Traceability',
      'No smoke evidence — run .harness/scripts/mcp-smoke.mjs');
  }
}

// MCP-04: HTTP transport auth mode — check source config
{
  const serverTs = path.join(cliDir, 'src', 'core', 'mcp', 'server.ts');
  if (fileExists(serverTs)) {
    const src = fs.readFileSync(serverTs, 'utf8');
    const hasApiKeyCheck = src.includes('apiKey') || src.includes('API_KEY') || src.includes('authorization');
    if (hasApiKeyCheck) {
      pass('MCP-04', 'HTTP Transport Requires Explicit Authentication Mode');
    } else {
      fail('MCP-04', 'HTTP Transport Requires Explicit Authentication Mode',
        'server.ts does not appear to check apiKey or authorization for HTTP transport');
    }
  } else {
    fail('MCP-04', 'HTTP Transport Requires Explicit Authentication Mode',
      `server.ts not found at ${serverTs}`);
  }
}

// MCP-05: Metrics emission (SHOULD)
{
  const metricsService = path.join(cliDir, 'src', 'core', 'mcp', 'metrics.service.ts');
  if (fileExists(metricsService)) {
    pass('MCP-05', 'MCP Calls Should Emit Metrics');
  } else {
    fail('MCP-05', 'MCP Calls Should Emit Metrics',
      `McpMetricsService not found at ${metricsService}`, false);
  }
}

// ──────────────────────────────────────────────────────────────────────────────
// Observability Telemetry
// ──────────────────────────────────────────────────────────────────────────────
console.log('\n▶ Observability Telemetry (observability)');

// OBS-EVD-01/02/03: Check for structured logger and observability context service
{
  const structuredLogger = path.join(cliDir, 'src', 'core', 'observability', 'structured-logger.ts');
  const errorReporter = path.join(cliDir, 'src', 'core', 'observability', 'error-reporter.ts');
  const timing = path.join(cliDir, 'src', 'core', 'observability', 'timing.ts');

  if (fileExists(structuredLogger)) {
    // CLI uses sessionId and operation as its correlation context (MCP tool calls, not HTTP services)
    const src = fs.readFileSync(structuredLogger, 'utf8');
    const telemetryService = path.join(cliDir, 'src', 'domain', 'services', 'tool-usage-telemetry.service.ts');
    const telSrc = fileExists(telemetryService) ? fs.readFileSync(telemetryService, 'utf8') : '';
    const hasCorrelation = src.includes('operation') || src.includes('context') ||
      telSrc.includes('sessionId') || telSrc.includes('correlationId');
    if (hasCorrelation) {
      pass('OBS-EVD-01', 'Production Paths Emit Trace Context');
    } else {
      fail('OBS-EVD-01', 'Production Paths Emit Trace Context',
        'No correlation context (operation/sessionId) found in structured-logger.ts or tool-usage-telemetry.service.ts');
    }

    const hasPiiSafe = src.includes('pii') || src.includes('PII') || src.includes('redact') || src.includes('sanitize');
    if (hasPiiSafe) {
      pass('OBS-EVD-02', 'Structured Logs Carry Request Context');
    } else {
      fail('OBS-EVD-02', 'Structured Logs Carry Request Context',
        'structured-logger.ts does not show PII-safe handling (redact/sanitize)', false);
    }
  } else {
    fail('OBS-EVD-01', 'Production Paths Emit Trace Context',
      `structured-logger.ts not found at ${structuredLogger}`);
    fail('OBS-EVD-02', 'Structured Logs Carry Request Context',
      `structured-logger.ts not found at ${structuredLogger}`, false);
  }

  if (fileExists(timing) || fileExists(errorReporter)) {
    pass('OBS-EVD-03', 'Service Health Metrics Are Reported');
  } else {
    fail('OBS-EVD-03', 'Service Health Metrics Are Reported',
      'Neither timing.ts nor error-reporter.ts found in observability/', false);
  }
}

// OBS-EVD-04: Dashboard reference in evidence (SHOULD)
{
  const smokeEvidence = path.join(evidenceDir, 'mcp-smoke.evidence.json');
  if (fileExists(smokeEvidence)) {
    const ev = JSON.parse(fs.readFileSync(smokeEvidence, 'utf8'));
    if (ev?.dashboardRef) {
      pass('OBS-EVD-04', 'Gate Evidence References Dashboard');
    } else {
      fail('OBS-EVD-04', 'Gate Evidence References Dashboard',
        'evidence file does not include dashboardRef — add when wiring to monitoring infra', false);
    }
  } else {
    fail('OBS-EVD-04', 'Gate Evidence References Dashboard',
      'No smoke evidence to check dashboardRef against', false);
  }
}

// ──────────────────────────────────────────────────────────────────────────────
// Summary
// ──────────────────────────────────────────────────────────────────────────────
const blockingFailures = failures.filter(f => f.blocking);
console.log(`\n${'─'.repeat(70)}`);
console.log(`Ruleset validation summary`);
console.log(`  Passed  : ${passed.length}`);
console.log(`  Warnings: ${warnings.length}`);
console.log(`  Failures: ${failures.length} (blocking: ${blockingFailures.length})`);

if (blockingFailures.length > 0) {
  console.error('\nBlocking failures:');
  for (const f of blockingFailures) {
    console.error(`  ✗ [${f.ruleId}] ${f.title}`);
    console.error(`      ${f.detail}`);
  }
  process.exit(1);
} else {
  console.log('\nRuleset validation passed.');
  process.exit(0);
}
