function readFileSafe(relativePath) {
  const full = path.join(root, relativePath);
  if (!fs.existsSync(full)) return "";
  return fs.readFileSync(full, "utf-8");
}

function extractSection(content, heading, level = 2) {
  const regex = new RegExp(
    `^#{${level}}\\s+${escapeRegex(heading)}\\s*$`,
    "m"
  );
  const match = content.match(regex);
  if (!match) return "";
  const start = match.index;
  const nextHeading = content.slice(start + match[0].length).match(
    new RegExp(`^#{1,${level}}\\s+`, "m")
  );
  const end = nextHeading
    ? start + match[0].length + nextHeading.index
    : content.length;
  return content.slice(start, end).trim();
}

function escapeRegex(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function stripBilingualNav(content) {
  return content
    .replace(/^>\s*\*\*Bilingual.*?\*\*.*$/gm, "")
    .replace(/^>\s*\*\*Navegación.*?\*\*.*$/gm, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function addWikiHeader(title, description) {
  return `# ${title}

> Auto-generated from repository documentation. Do not edit directly.
> Source: [github.com/beyondnetcode/evolith_arch32](https://github.com/beyondnetcode/evolith_arch32)

---

${description}

---

`;
}

function addWikiFooter(pageName) {
  const relatedPages = Object.keys(WIKI_SOURCES)
    .filter(f => f !== pageName + ".md")
    .map(f => {
      const name = f.replace(".md", "");
      const label = name.replace(/-/g, " ");
      return "- [" + label + "](https://github.com/beyondnetcode/evolith_arch32/wiki/" + name + ")";
    })
    .join("\n");
  const today = new Date().toISOString().split("T")[0];
  return "\n\n---\n\n## Related Pages\n\n" + relatedPages + "\n\n---\n\n*Auto-generated by sync-wiki.mjs - Last updated: " + today + "*\n";
}

