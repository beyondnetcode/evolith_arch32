#!/usr/bin/env node
/**
 * GT-460: regenerate the api command's MCP-surface catalog from the LIVE
 * @beyondnet/evolith-mcp server, so `smart-cli api --list` reflects reality
 * instead of hardcoded counts that drift as tools/resources are added.
 *
 * Usage: node scripts/gen-api-catalog.mjs
 * Emits: src/commands/api/api.catalog.generated.ts (checked in; refresh on drift).
 */
import { spawn } from 'child_process';
import { writeFileSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const cliRoot = resolve(here, '..');
// mcp-server lives at <core>/src/packages/mcp-server; cliRoot is <core>/src/sdk/cli.
const mcpMain = resolve(cliRoot, '../../packages/mcp-server/dist/main.js');
const outFile = resolve(cliRoot, 'src/commands/api/api.catalog.generated.ts');

function collect() {
  return new Promise((resolvePromise, reject) => {
    const child = spawn('node', [mcpMain], {
      env: { ...process.env, TRANSPORT: 'stdio', MCP_ALLOW_NO_AUTH: '1' },
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    let out = '';
    child.stdout.on('data', (d) => (out += d.toString()));
    child.on('error', reject);
    const send = (m) => child.stdin.write(JSON.stringify(m) + '\n');
    setTimeout(() => send({ jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: '2024-11-05', capabilities: {}, clientInfo: { name: 'gen', version: '0' } } }), 300);
    setTimeout(() => { send({ jsonrpc: '2.0', method: 'notifications/initialized' }); send({ jsonrpc: '2.0', id: 2, method: 'tools/list' }); }, 900);
    setTimeout(() => send({ jsonrpc: '2.0', id: 3, method: 'resources/list' }), 1300);
    setTimeout(() => {
      child.kill();
      const msgs = out.split('\n').filter((l) => l.trim().startsWith('{')).map((l) => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean);
      const tools = msgs.find((m) => m.id === 2)?.result?.tools ?? [];
      const resources = msgs.find((m) => m.id === 3)?.result?.resources ?? [];
      if (!tools.length) return reject(new Error('No tools returned from MCP server'));
      resolvePromise({ tools, resources });
    }, 2600);
  });
}

const clean = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();

const { tools, resources } = await collect();

const toolEntries = tools
  .map((t) => ({ name: clean(t.name), description: clean(t.description) }))
  .sort((a, b) => a.name.localeCompare(b.name));
const resourceEntries = resources
  .map((r) => ({ uri: clean(r.uri), name: clean(r.name), description: clean(r.description) }))
  .sort((a, b) => a.uri.localeCompare(b.uri));

const banner = `// AUTO-GENERATED by scripts/gen-api-catalog.mjs from the live @beyondnet/evolith-mcp
// server (tools/list + resources/list). Do NOT edit by hand — run
// \`npm run gen:api-catalog\` to refresh. Source of truth: the MCP server (GT-460).
`;
const body =
  banner +
  `\nimport type { ApiEntry, ApiResource } from './api.catalog';\n\n` +
  `export const GENERATED_TOOLS: ApiEntry[] = ${JSON.stringify(toolEntries, null, 2)};\n\n` +
  `export const GENERATED_RESOURCES: ApiResource[] = ${JSON.stringify(resourceEntries, null, 2)};\n`;

writeFileSync(outFile, body, 'utf8');
console.log(`✓ Wrote ${outFile}`);
console.log(`  tools: ${toolEntries.length} · resources: ${resourceEntries.length}`);
