function extractStats() {
  const tracking = readFileSafe(
    "reference/core/control-center/gap-tracking.md"
  );
  const doneMatch = tracking.match(/(\d+)\s*\/\s*312\s*done/);
  const openMatch = tracking.match(/(\d+)\s*pending/);
  return {
    totalGaps: 312,
    doneGaps: doneMatch ? doneMatch[1] : "290",
    openGaps: openMatch ? openMatch[1] : "22",
  };
}

// ─── Fingerprint & Diff Detection ──────────────────────────────────────────────

function computeFingerprint() {
  const sources = [];
  for (const page of Object.values(WIKI_SOURCES)) {
    for (const f of page.files) {
      const content = readFileSafe(f);
      sources.push(content);
    }
  }
  return createHash("sha256").update(sources.join("\n---\n")).digest("hex");
}

function isWikiStale() {
  if (!fs.existsSync(fingerprintFile)) return true;
  const stored = fs.readFileSync(fingerprintFile, "utf-8").trim();
  return stored !== computeFingerprint();
}

function saveFingerprint() {
  fs.mkdirSync(wikiDir, { recursive: true });
  fs.writeFileSync(fingerprintFile, computeFingerprint());
}

// ─── Main ──────────────────────────────────────────────────────────────────────

function main() {
  const args = process.argv.slice(2);
  const force = args.includes("--force");
  const check = args.includes("--check");

  if (check) {
    if (isWikiStale()) {
      console.log("⚠️  Wiki is stale — documentation has changed since last sync.");
      process.exit(1);
    }
    console.log("✅ Wiki is up to date.");
    process.exit(0);
  }

  if (!force && !isWikiStale()) {
    console.log("✅ Wiki is already up to date. Use --force to regenerate.");
    process.exit(0);
  }

  console.log("📝 Generating Wiki pages...");

  fs.mkdirSync(wikiDir, { recursive: true });

  let generated = 0;
  for (const [pageName, config] of Object.entries(WIKI_SOURCES)) {
    const sources = {};
    for (const f of config.files) {
      sources[f] = readFileSafe(f);
    }
    const content = config.transform(sources);
    const outPath = path.join(wikiDir, pageName);
    fs.writeFileSync(outPath, content);
    generated++;
    console.log(`  ✅ ${pageName}`);
  }

  saveFingerprint();
  console.log(`\n📦 Generated ${generated} wiki pages in reference/wiki/`);
  console.log("   Run 'git add reference/wiki/' to include in commit.");
}

main();
