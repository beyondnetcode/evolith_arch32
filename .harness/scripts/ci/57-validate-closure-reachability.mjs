#!/usr/bin/env node
/**
 * GT-697 — the detector for the failure mode nothing else in this repository can see:
 * a gap closed against code that production never reaches.
 *
 * WHY THIS EXISTS, measured rather than asserted. On 2026-08-15 an audit of this
 * repository established the loop the owner had been feeling: gaps close in a median
 * of 0-1 days, and a WRONG closure is discovered in a mean of 43.8 days (min 26, max
 * 53) — always by one human re-reading the board, never by a guard, a test or the
 * engine. A ~40x asymmetry between closing and detecting is the whole circle.
 *
 * `GT-321` is the archetype: closed against `AuditService`, whose only `new` in the
 * entire repository is in its own specs. `GT-266` is the same shape — a provisioning
 * service registered as a Nest provider that nothing ever calls. Both were ticked,
 * both were DONE, and both stayed that way for 49 and 51 days.
 *
 * WHAT IT CHECKS
 * For every closure record, every exported class in the PRODUCTION source it names as
 * evidence must have at least one production call site: constructed, injected by
 * type, extended, or bound with `useClass`. A class whose only references are its own
 * file, a spec, an import line or a bare provider registration is REACHABLE BY NOBODY,
 * and a closure resting on it did not deliver what it claimed.
 *
 * WHAT IT DELIBERATELY DOES NOT CHECK, and why each exclusion is not a loophole:
 *   - Framework-constructed classes (`@Module`, `@Controller`, `@Command`, DTOs). Nest
 *     and nest-commander build these from metadata; they have no literal call site BY
 *     DESIGN. Including them made the detector fire on every entry point in the repo,
 *     which is how a check gets muted within a week.
 *   - `*Error` subclasses thrown in their own file and matched by `instanceof`. Same
 *     reasoning: zero external construction is their normal shape.
 * Both exclusions were added only after they were OBSERVED producing false positives,
 * and the calibration cases below prove they did not also blind the detector.
 *
 * CALIBRATION IS PART OF THE GUARD, not a note in a commit message. `CALIBRATION`
 * lists the two gaps the owner refuted by hand that have this shape. If a future edit
 * stops detecting them, this guard fails on itself — a detector that cannot catch the
 * cases that motivated it is worse than none, because it certifies silence.
 *
 * NO REPORT MODE. The same audit found guard 41 printing its own defects and exiting
 * 0 with the words "THIS IS NOT A PASS". That is not repeated here. The findings
 * that existed when this guard was written are frozen in a baseline; anything NEW
 * fails, and an entry that is fixed but left in the baseline ALSO fails, so the
 * baseline can only shrink.
 *
 * Exits 1 on a new unreachable closure, on a stale baseline entry, or if calibration
 * breaks. Exits 0 only when every closure's production surface is reachable or
 * explicitly dispositioned.
 */

import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { assertScanned } from '../lib/coverage.mjs';

const ROOT = process.argv.includes('--root')
  ? process.argv[process.argv.indexOf('--root') + 1]
  : process.cwd();

const EVIDENCE = join(ROOT, 'reference/core/control-center/evidence/gap-closure-evidence.json');
const BASELINE = join(ROOT, '.harness/scripts/ci/closure-reachability-baseline.json');
const WRITE_BASELINE = process.argv.includes('--write-baseline');

/** Gaps the owner refuted BY HAND that have exactly this shape. See the docblock. */
const CALIBRATION = ['GT-321', 'GT-266'];

/**
 * Files whose classes NestJS and nest-commander construct from metadata. Verified
 * against the tree rather than assumed — see `frameworkConstructed`.
 */
const FRAMEWORK_FILE =
  /\.(module|controller|command|wizard|middleware|guard|interceptor|filter|dto|resolver|strategy)\.ts$|[./]dtos?[./]/;
const isProdEvidence = (p) =>
  /^src\//.test(p) &&
  // GT-698 — test doubles live under `src/**/test/mocks/`, a PRODUCTION path by
  // extension but consumed only by specs, which this detector deliberately does not
  // scan. `MockLogger` and `MockConfigParser` were reported unreachable for exactly
  // that reason; they are reachable, just not from where the detector is allowed to
  // look.
  !/\.spec\.|\.test\.|__tests__|[/\\](test|tests|mocks)[/\\]|[/\\]dist[/\\]|fixtures?/.test(p) &&
  /\.ts$/.test(p);

function productionSources() {
  const out = new Map();
  const src = join(ROOT, 'src');
  if (!existsSync(src)) return out;
  (function walk(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name);
      if (entry.isDirectory()) {
        // `sdk/cli/rulesets` is generated by `copy-rulesets` and gitignored — counting
        // it would double every symbol and hide real orphans behind its copies.
        if (/node_modules|[/\\]dist([/\\]|$)|coverage|\.git|sdk[/\\]cli[/\\]rulesets/.test(p)) continue;
        walk(p);
      } else if (/\.ts$/.test(entry.name) && !/\.spec\.|\.test\./.test(entry.name)) {
        out.set(p.slice(ROOT.length + 1), readFileSync(p, 'utf8'));
      }
    }
  })(src);
  return out;
}

const sources = productionSources();

function frameworkConstructed(text, cls, file) {
  // FILE CONVENTION, not syntax. Two syntactic attempts failed here and the second
  // was worse than the first: a fixed 4000-character lookback for the decorator
  // missed `AppModule`, whose `@Module({...})` literal starts 4596 characters before
  // the class, and replacing it with "nearest preceding @" matched JSDoc tags and
  // grew the baseline from 70 to 76. Hand-rolling a TypeScript parser with regexes
  // is the exact trade this repository has refused three times for the product; it
  // is refused here too.
  //
  // The convention is verifiable instead of assumed: across the 90 files matching
  // these suffixes there are 111 exported classes, 78 in a file carrying a framework
  // decorator and the other 33 all DTOs. Nest enforces the naming, so the file name
  // is a sounder signal than anything a regex can recover from the syntax.
  if (FRAMEWORK_FILE.test(file)) return true;
  if (/Error$/.test(cls) && new RegExp(`(throw new ${cls}|instanceof ${cls})`).test(text)) return true;

  // GT-698 — REGISTRATION IS THE CALL SITE for a lifecycle class, and this exclusion
  // exists because the detector got one wrong and said so.
  //
  // `RulesetCorpusWarmupService` was reported as unreachable and hand-described in
  // GT-698's own row as "referenced by nothing at all". That was FALSE. It is a
  // provider in `app.module.ts:123` implementing `OnApplicationBootstrap`, and the
  // closure that named it has runner evidence of it executing: "Ruleset corpus
  // loaded at startup: 393 rules". Nest invokes the hook; nothing in the codebase
  // ever needs to call it.
  //
  // BOTH conditions are required. A lifecycle class nobody registers really is dead,
  // and excluding on the interface alone would hide exactly that.
  const declaration = text.slice(text.indexOf(`export class ${cls}`), text.indexOf(`export class ${cls}`) + 300);
  const isLifecycle =
    /implements\s+[^{]*\b(OnApplicationBootstrap|OnModuleInit|OnModuleDestroy|OnApplicationShutdown|NestMiddleware|CanActivate|NestInterceptor|ExceptionFilter|PipeTransform)\b/.test(
      declaration,
    );
  if (isLifecycle) {
    for (const [other, otherText] of sources) {
      if (other === file) continue;
      if (/\.module\.ts$/.test(other) && new RegExp(`\\b${cls}\\b`).test(otherText)) return true;
    }
  }
  return false;
}

/**
 * GT-698 — the `export const x = new X()` singleton, found by triage.
 *
 * `hasProductionCallSite` skips the declaring file, so a class constructed into a
 * module-level singleton in its own file looks unreached. It is not: what travels is
 * the CONST. `CommandExecutor`, `ErrorReporter` and `GateRoleEnforcer` were all
 * reported unreachable while their singletons are imported across production.
 *
 * The const must actually be CONSUMED elsewhere. The six `GT-346` providers
 * (`DockerProvider`, `NpmProvider`, `NxProvider`, `PythonProvider`, `DotnetProvider`,
 * `GitHubActionsProvider`) construct singletons that nobody imports, and they stay
 * flagged — which is the whole point of requiring the second half.
 */
function singletonIsConsumed(cls, declaringFile, text) {
  let konst = null;
  for (const line of text.split('\n')) {
    const m = line.match(new RegExp(`^export\\s+const\\s+(\\w+)\\b.*=\\s*new\\s+${cls}\\s*\\(`));
    if (m) { konst = m[1]; break; }
  }
  if (!konst) return false;
  for (const [file, other] of sources) {
    if (file === declaringFile) continue;
    if (new RegExp(`\\b${konst}\\b`).test(other)) return true;
  }
  return false;
}

function hasProductionCallSite(cls, declaringFile) {
  const uses = new RegExp(
    `(new\\s+${cls}\\s*\\(|:\\s*${cls}\\b|<${cls}>|extends\\s+${cls}\\b|@Inject\\(${cls}\\)|useClass:\\s*${cls}\\b)`,
  );
  for (const [file, text] of sources) {
    if (file === declaringFile) continue;
    // Import and re-export lines are NOT use. GT-266 was registered as a provider and
    // exported from its module, and still nothing called it.
    const body = text
      .split('\n')
      .filter((l) => !/^\s*import\s/.test(l) && !/^\s*export\s+\{/.test(l))
      .join('\n');
    if (uses.test(body)) return true;
  }
  return false;
}

const raw = JSON.parse(readFileSync(EVIDENCE, 'utf8'));
const records = Array.isArray(raw) ? raw : (raw.closures ?? raw.records ?? Object.values(raw).find(Array.isArray));

const found = new Map();
let classesScanned = 0;
for (const record of records) {
  for (const file of (record.evidence ?? []).filter(isProdEvidence)) {
    const text = sources.get(file);
    if (text === undefined) continue; // a deleted file is a different signal, not this one
    for (const match of text.matchAll(/export class ([A-Za-z_]\w*)/g)) {
      const cls = match[1];
      if (frameworkConstructed(text, cls, file)) continue;
      classesScanned++;
      if (!hasProductionCallSite(cls, file) && !singletonIsConsumed(cls, file, text)) {
        const key = `${record.id}::${cls}`;
        if (!found.has(key)) found.set(key, { gap: record.id, cls, file, closedAt: record.closedAt });
      }
    }
  }
}

// GT-578 — a guard that scanned nothing did not run.
assertScanned(records.length, { what: 'closure records', where: EVIDENCE });
assertScanned(classesScanned, { what: 'exported classes named as closure evidence', where: EVIDENCE });

if (WRITE_BASELINE) {
  const entries = [...found.values()].sort((a, b) => a.gap.localeCompare(b.gap) || a.cls.localeCompare(b.cls));
  writeFileSync(
    BASELINE,
    `${JSON.stringify(
      {
        $comment:
          'GT-697 — closures resting on a class production never reaches, frozen when the detector was written. ' +
          'This list may only SHRINK. Removing an entry requires either wiring the class or reopening the gap. ' +
          'Regenerate with --write-baseline ONLY when deliberately re-baselining, and say so in the commit.',
        capturedOn: process.env.CAPTURE_DATE ?? '',
        entries,
      },
      null,
      2,
    )}\n`,
  );
  console.log(`baseline written: ${entries.length} entries -> ${BASELINE}`);
  process.exit(0);
}

const baseline = existsSync(BASELINE) ? JSON.parse(readFileSync(BASELINE, 'utf8')) : { entries: [] };
const baselined = new Set(baseline.entries.map((e) => `${e.gap}::${e.cls}`));

const appeared = [...found.keys()].filter((k) => !baselined.has(k));
const fixed = [...baselined].filter((k) => !found.has(k));
const calibrationLost = CALIBRATION.filter(
  (gap) => ![...found.keys(), ...baselined].some((k) => k.startsWith(`${gap}::`)),
);

if (calibrationLost.length > 0) {
  console.error('✗ 57-validate-closure-reachability: THE DETECTOR NO LONGER DETECTS ITS OWN CALIBRATION CASES.\n');
  for (const gap of calibrationLost) console.error(`    ${gap} was refuted by hand and this guard can no longer see it`);
  console.error(
    '\n  These two gaps are the reason this guard exists. If an edit stops them being\n' +
      '  detected, the guard now certifies a silence it has not earned. Fix the detector,\n' +
      '  or delete it — do not leave it passing.\n',
  );
  process.exit(1);
}

if (appeared.length > 0 || fixed.length > 0) {
  console.error('✗ 57-validate-closure-reachability: the closure ledger and the code disagree.\n');
  for (const key of appeared) {
    const e = found.get(key);
    console.error(`    NEW   ${e.gap} (closed ${e.closedAt}) rests on \`${e.cls}\`, which no production code reaches`);
    console.error(`          ${e.file}`);
  }
  for (const key of fixed) {
    console.error(`    STALE ${key} is in the baseline and is now reachable — remove the entry`);
  }
  console.error(
    '\n  A closure naming a class nothing constructs is the shape of GT-321 and GT-266:\n' +
      '  ticked, DONE, and wrong for 49 and 51 days before a human noticed. Either wire the\n' +
      '  class, or reopen the gap. The baseline may only shrink.\n',
  );
  process.exit(1);
}

console.log(
  `✓ 57-validate-closure-reachability: ${classesScanned} class(es) across ${records.length} closure(s); ` +
    `${found.size} unreachable, all dispositioned in the baseline; calibration cases ${CALIBRATION.join(', ')} still detected.`,
);
